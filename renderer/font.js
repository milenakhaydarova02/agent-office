  // Draw text with each font pixel as an s×s block; x/y are screen pixels.
  function draw(ctx, text, x, y, color, s = 1) {
    ctx.fillStyle = color;
    let cx = x;
    for (const ch of norm(text)) {
      const rows = g[ch] || g['?'];
      for (let r = 0; r < 7; r++) {
        const bits = rows[r];
        if (!bits) continue;
        for (let c = 0; c < 5; c++) {
          if (bits & (16 >> c)) ctx.fillRect(cx + c * s, y + r * s, s, s);
        }
      }
      cx += ADV * s;
    }
  }

  function width(text) {
    return norm(text).length * ADV - 1;
  }

  // Greedy word wrap into at most maxLines lines of maxChars.
  function wrap(text, maxChars, maxLines) {
    const words = norm(text).trim().split(' ');
    const lines = [];
    let cur = '';
    for (let w of words) {
      while (w.length > maxChars) {
        if (cur) { lines.push(cur); cur = ''; }
        lines.push(w.slice(0, maxChars));
        w = w.slice(maxChars);
      }
      if (!cur) cur = w;
      else if ((cur + ' ' + w).length <= maxChars) cur += ' ' + w;
      else { lines.push(cur); cur = w; }
    }
    if (cur) lines.push(cur);
    if (lines.length > maxLines) {
      lines.length = maxLines;
      const last = lines[maxLines - 1];
      lines[maxLines - 1] = (last.length > maxChars - 3 ? last.slice(0, maxChars - 3) : last) + '...';
    }
    return lines;
  }

  return { draw, width, wrap, norm, ADV, LINE };
